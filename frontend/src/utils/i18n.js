/**
 * Get translation for key in target language, with fallback to English.
 */
export function t(key, lang = "en") {
  const selectedLang = TRANSLATIONS[lang] || TRANSLATIONS["en"];
  return selectedLang[key] || TRANSLATIONS["en"][key] || key;
}

/**
 * Format currency amount with appropriate symbol and numbering system.
 * Indian Rupee (INR) uses the Indian numbering system (e.g. 1,00,000.00).
 */
export function formatCurrency(amount, currencySymbol = "$", currencyCode = "USD") {
  const num = Number(amount) || 0;
  
  if (currencyCode === "INR" || currencySymbol === "₹") {
    // Format according to Indian Numbering System
    return `${currencySymbol}${num.toLocaleString("en-IN", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })}`;
  }

  return `${currencySymbol}${num.toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}
